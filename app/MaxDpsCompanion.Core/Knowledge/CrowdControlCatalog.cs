    private static CrowdControlEntry Cc(
        int id, string name, CcKind kind, CcDrCategory dr,
        bool single, bool aoe, int cdMs, bool auto, string className, params string[] specs)
    {
        // Only a stun/silence can be the automatic interrupt fallback. A
        // silence is allowed even when it is a beam/zone (Solar Beam, Ring of
        // Peace) because it does not break on damage and still stops a cast;
        // AoE STUNS remain manual (the legacy flag already demotes Shockwave /
        // Leg Sweep). Everything else is manual.
        var role = auto && kind is CcKind.Stun or CcKind.Silence
            && (single || kind == CcKind.Silence)
            ? CcRole.InterruptFallback
            : CcRole.Manual;
        var meta = Meta.TryGetValue(id, out var m)
            ? m
            : new CcMeta(0, null, false, false, 100);
        return new CrowdControlEntry(id, name, kind, dr, single, aoe, cdMs, auto, className, specs)
        {
            Role = role,
            BaseDurationMs = meta.DurationMs,
            BreaksOnDamage = meta.Breaks ?? DefaultBreaks(kind),
            RequiresStealth = meta.Stealth,
            RequiresOutOfCombat = meta.OutOfCombat,
            Priority = meta.Priority,
        };
    }

    private static bool DefaultBreaks(CcKind kind) => kind switch
    {
        CcKind.Stun or CcKind.Silence or CcKind.Root => false,
        CcKind.Disorient or CcKind.Incapacitate or CcKind.Fear
            or CcKind.Sleep or CcKind.Banish or CcKind.Subjugate
            or CcKind.Knockback => true,
        _ => false,
    };
