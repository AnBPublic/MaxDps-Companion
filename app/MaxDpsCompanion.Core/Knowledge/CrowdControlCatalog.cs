namespace MaxDpsCompanion;

/// <summary>
/// WoW's diminishing-returns categories, used ONLY for the companion's own
/// conservative "do not auto-chain" memory. The companion never infers the
/// target's live DR state (that is unobservable in Midnight); it remembers what
/// it itself applied and fails open whenever that memory is unknown.
/// </summary>
internal enum CcDrCategory
{
    Unknown = 0,
    Stun,
    Incapacitate,
    Disorient,
    Silence,
    Root,
    Fear,
}

/// <summary>
/// What the companion is allowed to do with a curated CC row.
/// <see cref="InterruptFallback"/> is the ONLY automatic role: a single-target
/// stun/silence that may stop a live cast when the class interrupt is not
/// available. Proactive break-on-damage CC (Blind, Gouge, Sap, Polymorph,
/// Fear, ...) is manual-only; the companion may hold attacks after the player
/// presses it, but it never generates that press itself.
/// </summary>
internal enum CcRole
{
    /// <summary>Manual by design: the companion never auto-casts it.</summary>
    Manual = 0,
    /// <summary>Casting-only interrupt substitute (single-target stun/silence).</summary>
    InterruptFallback = 1,
    /// <summary>Manual proactive CC (kept for UI/audit; never auto-cast).</summary>
    Proactive = 2,
}

/// <summary>
/// One curated crowd-control entry (v3.4.0 CC appendix). The list is
/// hand-curated and every id is VERIFIED against the live-client DB2 export
/// (<c>Knowledge/spell-verification.json</c>, <c>verified:true</c>) plus a
/// vendor/curated row. Unverified ids are deliberately absent — an empty list
/// is an honest empty state, never a guessed id.
///
/// v4.2.0: <see cref="AutoEligible"/> is derived from <see cref="Role"/> and is
/// true ONLY for the single-target stun/silence interrupt fallback (Kidney
/// Shot 408, Hammer of Justice 853, Storm Bolt 107570, Asphyxiate 221562,
/// Mighty Bash 5211, Intimidation 19577, Silence 15487, Solar Beam 78675; the
/// AoE silence-zone Ring of Peace stays the one explicit exception). Blind,
/// Gouge, Sap, Polymorph, Fear, Hex, Repentance and every other break-on-damage
/// row are <see cref="CcRole.Manual"/> and can never be generated by the
/// companion, even with the global CC toggle ON. Shockwave (46968) and Leg
/// Sweep (119381) remain manual AoE stuns (no enemy-count signal). Every auto
/// Stun/Silence row is casting-gated by the CC provider and by
/// <see cref="CrowdControlVetoes.InterruptFallbackVeto"/>; a blind stun is
/// never generated.
/// </summary>
internal sealed record CrowdControlEntry(
    int SpellId,
    string Name,
    CcKind Kind,
    CcDrCategory Dr,
    bool SingleTarget,
    bool Aoe,
    int CdMs,
    bool LegacyAutoEligible,
    string ClassName,
    string[] Specs)
{
    /// <summary>Automatic role. Only interrupt-fallback rows are auto-eligible.</summary>
    public CcRole Role { get; init; } = CcRole.Manual;

    /// <summary>
    /// Curated base duration in milliseconds. Kidney Shot uses the conservative
    /// 2 s minimum (the live value scales 2-6 s by combo points, which the
    /// companion cannot observe). Used for DR maths and the CC attack guard.
    /// </summary>
    public int BaseDurationMs { get; init; }

    /// <summary>Damage breaks the effect (Blind, Gouge, Sap, Polymorph, Fear, ...).</summary>
    public bool BreaksOnDamage { get; init; }

    /// <summary>Requires stealth (Sap, Cheap Shot).</summary>
    public bool RequiresStealth { get; init; }

    /// <summary>Requires the player to be out of combat (Sap).</summary>
    public bool RequiresOutOfCombat { get; init; }

    /// <summary>Lower values are offered first in the interrupt-fallback pool.</summary>
    public int Priority { get; init; } = 100;

    /// <summary>True when the entry is one the companion may generate automatically.</summary>
    public bool AutoEligible => Role == CcRole.InterruptFallback;

    /// <summary>True when the entry is an area effect.</summary>
    public bool IsAoe => Aoe || !SingleTarget;
}

/// <summary>
/// The curated CC registry (read path consumed by
/// <see cref="AbilityCatalog.CrowdControlFor(string?, string?, int)"/>). Pure
/// static data; no game API, no wire change.
/// </summary>
internal static class CrowdControlCatalog
{
    // Lazy so the CcMeta table below is initialized before the first Build()
    // call (static field initializers run in textual order), and thread-safe
    // for the test/UI readers that touch the catalog from parallel sessions.
    private static readonly Lazy<CrowdControlEntry[]> LazyEntries = new(Build);
    private static CrowdControlEntry[] Entries => LazyEntries.Value;

    /// <summary>All curated CC entries for a class+spec (empty when none/unknown).</summary>
    public static IReadOnlyList<CrowdControlEntry> For(string? className, string? specName)
    {
        if (className is null || specName is null) return [];
        var result = new List<CrowdControlEntry>();
        foreach (var entry in Entries)
        {
            if (!Matches(entry, className, specName)) continue;
            result.Add(entry);
        }
        return result;
    }

    /// <summary>The curated CC entry for one spell id on a class+spec, or null.</summary>
    public static CrowdControlEntry? Find(string? className, string? specName, int spellId)
    {
        if (className is null || specName is null || spellId <= 0) return null;
        foreach (var entry in Entries)
        {
            if (entry.SpellId != spellId) continue;
            if (Matches(entry, className, specName)) return entry;
        }
        return null;
    }

    /// <summary>
    /// Finds a curated CC row by spell id without class/spec knowledge. Used by
    /// the engine's break-on-damage guard for a player hotbar press and by the
    /// scheduler when it records a CC send.
    /// </summary>
    public static CrowdControlEntry? FindAny(int spellId)
    {
        if (spellId <= 0) return null;
        foreach (var entry in Entries)
            if (entry.SpellId == spellId) return entry;
        return null;
    }

    /// <summary>Every curated CC id (for audit/coverage tests).</summary>
    public static IReadOnlyList<int> AllIds()
    {
        var ids = new int[Entries.Length];
        for (var i = 0; i < Entries.Length; i++) ids[i] = Entries[i].SpellId;
        return ids;
    }

    private static bool Matches(CrowdControlEntry entry, string className, string specName)
    {
        if (!string.Equals(entry.ClassName, className, StringComparison.OrdinalIgnoreCase)) return false;
        foreach (var spec in entry.Specs)
            if (string.Equals(spec, specName, StringComparison.OrdinalIgnoreCase)) return true;
        return false;
    }

